/**
 * 一条每日格言：正文 + 出处。
 *
 * 出处单独成字段，是因为「行远自迩，登高自卑」这种句子不挂来源时，
 * 看起来就像 App 作者自己编的鸡汤 —— 挂上《礼记》，分量完全不同。
 */
